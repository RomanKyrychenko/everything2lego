"""Build a real-vs-ours discriminator dataset.  Three views (30, 120,
210 — same angles as the project's default render) per model, cached as
PNGs under $LEGO_DATA/analysis/discriminator/{real,ours}/<set>_<view>.png.

    python tools/learn/discriminator_dataset.py --n-real 150 --n-ours 50

Real: OMR .mpd files with kind=building from set_kinds.csv (filtered to
files that actually exist in $LEGO_DATA/omr/files).  Ours: generated by
tools/sampler_demo.py from randomly-picked building meshes in
examples/ (seeds 0..n-ours-1), native engine, --snot-decorate off.

Idempotent: skips renders whose output file already exists.  Prints a
summary of what landed."""
from __future__ import annotations

import argparse
import csv
import os
import random
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))

DATA = Path(os.environ.get("LEGO_DATA", "/Volumes/PRO-G40/lego_data"))
OMR = DATA / "omr" / "files"
SET_KINDS = DATA / "analysis" / "set_kinds.csv"
OUT = DATA / "analysis" / "discriminator"
VIEWS = (30, 120, 210)
SIZE = 128


def _render(ldr: Path, out_png: Path, view: int) -> bool:
    """Render one view with LDView; returns True on success."""
    if out_png.exists():
        return True
    out_png.parent.mkdir(parents=True, exist_ok=True)
    cmd = [sys.executable, str(ROOT / "tools" / "render_build.py"),
           str(ldr), str(out_png), "--views", str(view), "--size", str(SIZE)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0 or not out_png.exists():
        return False
    return True


def _building_omr(n: int, seed: int) -> list[Path]:
    """n OMR files whose set id is kind=building."""
    if not SET_KINDS.exists():
        return []
    building_ids = set()
    with SET_KINDS.open() as f:
        for row in csv.DictReader(f):
            if row.get("kind") == "building":
                building_ids.add(row["id"])
    files = []
    for f in sorted(OMR.glob("*.mpd")):
        sid = f.stem.split("_")[0]            # "10001-1_whatever" -> "10001-1"
        if sid in building_ids:
            files.append(f)
    random.Random(seed).shuffle(files)
    return files[:n]


def _ours_meshes() -> list[Path]:
    """Available building meshes to generate from."""
    out = []
    for d in (ROOT / "examples").iterdir():
        if d.is_dir():
            for g in d.glob("*.glb"):
                out.append(g)
    for g in (ROOT / "examples").glob("*.glb"):
        out.append(g)
    return sorted(set(out))


def _generate_ours(mesh: Path, seed: int, out_dir: Path, iters: int = 20000) -> Path | None:
    """Run sampler on `mesh` with `seed`; return the generated .ldr path."""
    sess = out_dir / f"{mesh.stem}_s{seed}"
    sess.mkdir(parents=True, exist_ok=True)
    ldr = sess / "model.ldr"
    if ldr.exists():
        return ldr
    cmd = [sys.executable, str(ROOT / "tools" / "sampler_demo.py"),
           str(mesh), str(sess), "--iters", str(iters), "--seed", str(seed),
           "--no-snot-decorate"]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
    if r.returncode != 0 or not ldr.exists():
        return None
    return ldr


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-real", type=int, default=150, help="OMR building sets")
    ap.add_argument("--n-ours", type=int, default=50, help="sampler-generated builds")
    ap.add_argument("--seed", type=int, default=0, help="seed for OMR sampling + ours")
    ap.add_argument("--iters", type=int, default=20000, help="sampler iters per build")
    ap.add_argument("--ours-scratch", type=Path, default=OUT / "_ours_scratch",
                     help="where sampler outputs live")
    args = ap.parse_args()

    real_dir = OUT / "real"
    ours_dir = OUT / "ours"
    real_dir.mkdir(parents=True, exist_ok=True)
    ours_dir.mkdir(parents=True, exist_ok=True)

    # Real
    real_files = _building_omr(args.n_real, args.seed)
    print(f"real: {len(real_files)} OMR building sets found", flush=True)
    r_ok = 0
    for i, ldr in enumerate(real_files):
        for v in VIEWS:
            png = real_dir / f"{ldr.stem}_v{v}.png"
            if _render(ldr, png, v):
                r_ok += 1
        if (i + 1) % 10 == 0:
            print(f"  rendered {i+1}/{len(real_files)} ({r_ok} images)", flush=True)
    print(f"real: {r_ok} images in {real_dir}", flush=True)

    # Ours
    meshes = _ours_meshes()
    if not meshes:
        print("no meshes in examples/ — skipping ours", flush=True)
        return
    print(f"ours: {len(meshes)} available meshes, generating {args.n_ours} builds", flush=True)
    o_ok = 0
    for i in range(args.n_ours):
        mesh = meshes[i % len(meshes)]
        seed = args.seed * 1000 + i
        ldr = _generate_ours(mesh, seed, args.ours_scratch, iters=args.iters)
        if ldr is None:
            print(f"  skip {mesh.stem} s={seed}: sampler failed", flush=True)
            continue
        for v in VIEWS:
            png = ours_dir / f"{mesh.stem}_s{seed}_v{v}.png"
            if _render(ldr, png, v):
                o_ok += 1
        if (i + 1) % 5 == 0:
            print(f"  rendered {i+1}/{args.n_ours} ({o_ok} images)", flush=True)
    print(f"ours: {o_ok} images in {ours_dir}", flush=True)


if __name__ == "__main__":
    main()
